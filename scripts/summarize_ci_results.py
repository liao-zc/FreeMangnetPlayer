"""Create a readable CI report from the Android emulator test artifacts."""
import json
import os
from pathlib import Path

root = Path("manual-shots")
root.mkdir(exist_ok=True)
status_file = root / "ui-regression-status.tsv"
script_status = []
if status_file.exists():
    for line in status_file.read_text(encoding="utf-8").splitlines():
        if "\t" in line:
            name, code = line.split("\t", 1)
            script_status.append((name, int(code)))
checks = []
for filename in ("library-verification.json", "preferences-verification.json", "pagination-verification.json"):
    source = root / filename
    if not source.exists():
        continue
    try:
        rows = json.loads(source.read_text(encoding="utf-8"))
    except Exception as exc:
        checks.append((filename, False, "Invalid JSON: " + str(exc)))
        continue
    if isinstance(rows, list):
        for row in rows:
            checks.append((row.get("check", filename), bool(row.get("passed")), row.get("reason", "")))
passed = sum(1 for _, ok, _ in checks if ok)
failed = len(checks) - passed
lines = [
    "# OmniPlayer emulator regression report", "",
    "Generated by `scripts/run_ui_regressions.sh`.", "",
    f"Recorded checks: {len(checks)}; passed: {passed}; failed: {failed}.", "",
    "## Suite results", "", "| Suite | Result |", "|---|---|"
]
for name, code in script_status:
    result = "PASS" if code == 0 else "FAIL (exit " + str(code) + ")"
    lines.append("| `" + name + "` | " + result + " |")
if not script_status:
    lines.append("| UI regression runner | No status file was produced |")
stage_status = root / "android-stage-status.tsv"
if stage_status.exists():
    for line in stage_status.read_text(encoding="utf-8").splitlines():
        if "\t" in line:
            name, code = line.split("\t", 1)
            result = "PASS" if code == "0" else "FAIL (exit " + code + ")"
            lines.append("| Android " + name + " | " + result + " |")
lines += ["", "## Build and emulator suite", "", "| Stage | Result |", "|---|---|"]
for key, label in (("OMNI_BUILD_OUTCOME", "APK and instrumentation build"), ("OMNI_EMULATOR_OUTCOME", "Android emulator suites")):
    value = os.environ.get(key, "not recorded")
    lines.append("| " + label + " | " + value + " |")
lines += ["", "## Individual checks", "", "| Check | Result | Detail |", "|---|---|---|"]
for name, ok, detail in checks:
    result = "PASS" if ok else "FAIL"
    lines.append("| " + str(name).replace("|", "/") + " | " + result + " | " + str(detail).replace("|", "/") + " |")
if not checks:
    lines.append("| No JSON checks recorded | NOT RUN | Suite may have stopped before recording checks. |")
lines += ["", "A failed or missing suite is not a passed product requirement. See workflow logs and uploaded screenshots/state JSON for diagnostics.", ""]
report = root / "OmniPlayer-CI-Report.md"
report.write_text("\n".join(lines), encoding="utf-8")
print(report)